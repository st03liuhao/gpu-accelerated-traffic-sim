"""Export the trained actor as a CUDA header of __constant__ weights for cuda/lc_policy.cuh.

    python -m lcrl.export_cuda --policy runs/ppo_v1/policy.pt --out cuda/lc_policy_weights.h
"""
import argparse

from .config import LON_DELTAS, NUM_LAT, NUM_LON, OBS_DIM, EGO_FEATURES, LANE_FEATURES, REL_LANES


def _arr(name, t):
    vals = ", ".join(f"{v:.9e}f" for v in t.detach().cpu().flatten().tolist())
    return f"__constant__ float {name}[{t.numel()}] = {{{vals}}};\n"


def export(net, path):
    a = net.actor
    layout = [f"//   [{i:2d}] ego.{n}" for i, n in enumerate(EGO_FEATURES)]
    base = len(EGO_FEATURES)
    for r, d in enumerate(REL_LANES):
        side = {-1: "left", 0: "current", 1: "right"}[d]
        layout += [f"//   [{base + r * len(LANE_FEATURES) + i:2d}] {side}.{n}" for i, n in enumerate(LANE_FEATURES)]
    with open(path, "w") as f:
        f.write("// Generated by lcrl/export_cuda.py -- do not edit.\n#pragma once\n")
        f.write(f"#define LC_OBS_DIM {OBS_DIM}\n#define LC_HIDDEN {net.hidden}\n")
        f.write(f"#define LC_NUM_LAT {NUM_LAT}\n#define LC_NUM_LON {NUM_LON}\n")
        f.write("#define LC_LON_DELTAS {" + ", ".join(f"{d}f" for d in LON_DELTAS) + "}\n")
        f.write("// Observation layout:\n" + "\n".join(layout) + "\n")
        for name, layer in (("lc_W1", a[0].weight), ("lc_b1", a[0].bias), ("lc_W2", a[2].weight),
                            ("lc_b2", a[2].bias), ("lc_W3", a[4].weight), ("lc_b3", a[4].bias)):
            f.write(_arr(name, layer))


if __name__ == "__main__":
    p = argparse.ArgumentParser()
    p.add_argument("--policy", required=True)
    p.add_argument("--out", default="cuda/lc_policy_weights.h")
    args = p.parse_args()
    from .train import load
    export(load(args.policy, "cpu"), args.out)
    print("wrote", args.out)
